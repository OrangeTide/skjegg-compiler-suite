#!/bin/sh
# bench.sh - deterministic instruction-count benchmark for the emulator.
#
# Each guest named in the corpus list is run under skj-run --stats, and the
# retired-instruction count is read back.  The interpreter counts
# instructions with no timing input, so that count is identical on every
# host (see doc/emulator.md), which makes it a reproducible benchmark metric
# where wall-clock time is not.
#
# The count is compared against a committed baseline.  A change in either
# direction fails the gate, because on a deterministic interpreter the only
# thing that moves an instruction count is a change in what the guest, or
# the code generated for it, actually does.  Review the change, then record
# the new numbers with --accept (make bench-accept) once it is intended.
#
# A guest whose binary is absent is skipped, not failed: its cross toolchain
# was not present at build time, so a machine with only one toolchain can
# still gate its own half of the corpus.
#
# Usage: bench.sh <skj-run> <build-dir> <list> <baseline> [--accept]

set -eu

SKJRUN=$1
BUILD=$2
LIST=$3
BASELINE=$4
ACCEPT=${5:-}

work=$(mktemp)
errf=$(mktemp)
trap 'rm -f "$work" "$errf"' EXIT

# Echo the retired-instruction count for guest $1.  The count prints on
# stderr regardless of the guest's exit code, so the exit code is ignored
# and an empty result means no stats line appeared at all.
run_count() {
    "$SKJRUN" --stats "$BUILD/$1" </dev/null >/dev/null 2>"$errf" || :
    grep -oE '[0-9]+ instructions' "$errf" | grep -oE '[0-9]+' | head -n1 || :
}

present=0
skipped=0
while read -r rel _rest; do
    case "$rel" in '' | \#*) continue ;; esac
    if [ ! -x "$BUILD/$rel" ]; then
        printf 'SKIP   %-34s (not built)\n' "$rel"
        skipped=$((skipped + 1))
        continue
    fi
    n=$(run_count "$rel")
    present=$((present + 1))
    if [ -z "$n" ]; then
        printf 'ERROR  %-34s (no stats; did not run)\n' "$rel"
        echo "$rel ERROR" >>"$work"
        continue
    fi
    echo "$rel $n" >>"$work"
done <"$LIST"

if [ "$ACCEPT" = "--accept" ]; then
    {
        echo "# instruction-count baseline, regenerated by: make bench-accept"
        echo "# guest-relpath  retired-instructions"
        sort "$work"
    } >"$BASELINE"
    printf '\naccepted %d guest(s) into %s (%d skipped)\n' \
        "$present" "$BASELINE" "$skipped"
    exit 0
fi

if [ ! -f "$BASELINE" ]; then
    echo "bench: no baseline at $BASELINE; run: make bench-accept" >&2
    exit 1
fi

fail=0
while read -r rel n; do
    if [ "$n" = ERROR ]; then
        fail=1
        continue
    fi
    want=$(awk -v k="$rel" '$1 == k { print $2 }' "$BASELINE")
    if [ -z "$want" ]; then
        printf 'NEW    %-34s %s  (not in baseline)\n' "$rel" "$n"
        fail=1
    elif [ "$n" = "$want" ]; then
        printf 'PASS   %-34s %s\n' "$rel" "$n"
    else
        d=$((n - want))
        pct=$(awk -v d="$d" -v w="$want" 'BEGIN { printf "%+.2f%%", 100 * d / w }')
        if [ "$d" -gt 0 ]; then dir=regressed; else dir=improved; fi
        printf 'FAIL   %-34s %s -> %s  (%+d, %s) [%s]\n' \
            "$rel" "$want" "$n" "$d" "$pct" "$dir"
        fail=1
    fi
done <"$work"

printf '\n%d benchmarked, %d skipped\n' "$present" "$skipped"
if [ "$fail" -ne 0 ]; then
    echo "bench: instruction counts changed; review, then: make bench-accept" >&2
    exit 1
fi
