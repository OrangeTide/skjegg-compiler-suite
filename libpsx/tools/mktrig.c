/* mktrig.c - host-side generator for the libpsx sine table (milestone 4).
 *
 * Emits a 1024-entry 16.16 fixed-point sine table (one full turn) as a C array,
 * so the target has trigonometry without an FPU or a runtime generator. Keeps
 * the math pipeline in-tree C with no external tool.
 *
 * Usage: mktrig <out.c>
 */

#include <math.h>
#include <stdio.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

#define N 1024

int
main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "usage: mktrig <out.c>\n");
        return 2;
    }
    FILE *f = fopen(argv[1], "w");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fprintf(f, "/* generated by mktrig: 16.16 sine, 1024 steps per turn */\n");
    fprintf(f, "const int psx_sintab[%d] = {\n", N);
    for (int i = 0; i < N; i++) {
        double s = sin(2.0 * M_PI * (double)i / (double)N);
        long v = (long)(s * 65536.0 + (s >= 0 ? 0.5 : -0.5));
        fprintf(f, "%ld,%s", v, (i % 8 == 7) ? "\n" : "");
    }
    fprintf(f, "\n};\n");
    fclose(f);
    return 0;
}
