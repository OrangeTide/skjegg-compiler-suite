/* Where the rasterised font atlas lives in VRAM, and its layout. 16 cells per
 * row, 6 rows, each cell 8x8: a 128x48 block. */
#define FONT_VX  704
#define FONT_VY  256
#define FONT_COLS 16

static psx_texinfo font_tex;
static int font_ready;

void
psx_debug_init(void)
{
    static uint16_t atlas[48 * 128];
    int idx, row, col;

    if (font_ready)
        return;

    for (idx = 0; idx < 95; idx++) {
        int cell_x = (idx % FONT_COLS) * 8;
        int cell_y = (idx / FONT_COLS) * 8;
        for (row = 0; row < 8; row++) {
            unsigned char bits = font8x8[idx][row];
            for (col = 0; col < 8; col++) {
                int ax = cell_x + col;
                int ay = cell_y + row;
                atlas[ay * 128 + ax] = (bits & (1u << col)) ? 0xFFFFu : 0x0000u;
            }
        }
    }

    psx_vram_upload(FONT_VX, FONT_VY, 128, 48, atlas);

    /* A 16-bit (direct colour) texture page. X base in 64-halfword units, Y
     * base 0 or 256; the texel offset within the page is 0 since the atlas sits
     * on a page boundary. */
    font_tex.tpage = (uint16_t)(((FONT_VX / 64) & 0xF) | (1u << 4) | (2u << 7));
    font_tex.clut = 0;
    font_tex.u = 0;
    font_tex.v = 0;
    font_tex.w = 128;
    font_tex.h = 48;
    font_ready = 1;
}

void
psx_debug_print(int x, int y, const char *s)
{
    if (!font_ready)
        psx_debug_init();

    for (; *s; s++, x += 8) {
        unsigned char c = (unsigned char)*s;
        if (c < 0x20 || c > 0x7E)
            continue;                       /* unprintable: leave a gap */
        int idx = c - 0x20;
        int u = (idx % FONT_COLS) * 8;
        int v = (idx / FONT_COLS) * 8;
        psx_draw_sprite_uv(&font_tex, x, y, u, v, 8, 8);
    }
}
