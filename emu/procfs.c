/* procfs.c : host-side content generation for the proc: pseudo filesystem.
 *
 * See procfs.h for the namespace.  The design the backlog item asks for is a
 * generated-content convenience: a handler is handed a growable buffer and a
 * printf helper and simply writes the text, and the layer owns the buffer's
 * growth and lifetime.  `struct gbuf` / gbuf_printf are that helper; a future
 * pseudo file reuses them. */

#include "procfs.h"
#include "sched.h"
#include "fs.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdarg.h>
#include <errno.h>

/****************************************************************
 * gbuf: a growable byte buffer with a printf-style append
 ****************************************************************/

struct gbuf {
    char  *p;
    size_t len;
    size_t cap;
};

/* Ensure room for `need` more bytes.  Returns 0, or -1 if the allocation
 * failed (the buffer is left usable at its old size). */
static int
gbuf_reserve(struct gbuf *b, size_t need)
{
    size_t want = b->len + need;
    size_t cap;
    char *np;

    if (want <= b->cap)
        return 0;
    cap = b->cap ? b->cap : 256;
    while (cap < want)
        cap *= 2;
    np = realloc(b->p, cap);
    if (!np)
        return -1;
    b->p = np;
    b->cap = cap;
    return 0;
}

static void
gbuf_printf(struct gbuf *b, const char *fmt, ...)
{
    va_list ap, ap2;
    int n;

    va_start(ap, fmt);
    va_copy(ap2, ap);
    n = vsnprintf(NULL, 0, fmt, ap);        /* measure */
    va_end(ap);
    if (n > 0 && gbuf_reserve(b, (size_t)n + 1) == 0) {
        vsnprintf(b->p + b->len, (size_t)n + 1, fmt, ap2);
        b->len += (size_t)n;
    }
    va_end(ap2);
}

static void
gbuf_free(struct gbuf *b)
{
    free(b->p);
    b->p = NULL;
    b->len = b->cap = 0;
}

/****************************************************************
 * The open handle
 ****************************************************************/

enum { PF_ROOT, PF_PID, PF_FILE };          /* node kinds */

struct procfs_open {
    struct sched *S;
    int          kind;                      /* PF_* */
    int          slot;                      /* target process, for PF_PID/PF_FILE */
    struct gbuf  buf;                        /* PF_FILE: generated bytes */
    int64_t      pos;                        /* PF_FILE: read cursor */
    int          index;                      /* PF_ROOT/PF_PID: getdent cursor */
};

/****************************************************************
 * Path resolution
 ****************************************************************/

/* Parse a capability-relative path into a node (kind + target slot).  Returns 0
 * on success, or a negative errno.  "self" resolves to caller_slot. */
static int
resolve(struct sched *S, int caller_slot, const char *rel, int *kind, int *slot)
{
    const char *p = rel;
    const char *comp;
    size_t clen;
    int id_slot;

    while (*p == '/')
        p++;
    if (p[0] == 0 || (p[0] == '.' && p[1] == 0)) {
        *kind = PF_ROOT;
        *slot = -1;
        return 0;
    }

    comp = p;                               /* first path component */
    while (*p && *p != '/')
        p++;
    clen = (size_t)(p - comp);
    while (*p == '/')
        p++;

    if (clen == 4 && memcmp(comp, "self", 4) == 0) {
        id_slot = caller_slot;
    } else {
        unsigned long id = 0;
        size_t i;
        for (i = 0; i < clen; i++) {
            if (comp[i] < '0' || comp[i] > '9')
                return -ENOENT;
            id = id * 10 + (unsigned long)(comp[i] - '0');
        }
        if (id < 1 || id > SKJ_MAX_PROC)
            return -ENOENT;
        id_slot = (int)id - 1;
    }
    if (id_slot < 0 || id_slot >= SKJ_MAX_PROC || !S->procs[id_slot])
        return -ENOENT;

    if (*p == 0) {                          /* proc:<id> */
        *kind = PF_PID;
        *slot = id_slot;
        return 0;
    }
    if (strcmp(p, "status") == 0) {         /* proc:<id>/status */
        *kind = PF_FILE;
        *slot = id_slot;
        return 0;
    }
    return -ENOENT;
}

/****************************************************************
 * Content generation
 ****************************************************************/

static const char *
state_name(const proc *pr)
{
    if (pr->done)
        return "done";
    if (pr->zombie)
        return "zombie";
    if (pr->io_blocked)
        return "blocked";
    if (pr->g.sleeping)
        return "sleeping";
    return "running";
}

/* Fill b with the status file for the process in `slot`. */
static void
gen_status(struct sched *S, int slot, struct gbuf *b)
{
    const proc *pr = S->procs[slot];

    gbuf_printf(b, "Pid:\t%d\n", slot + 1);
    gbuf_printf(b, "State:\t%s\n", state_name(pr));
    gbuf_printf(b, "Parent:\t%d\n", pr->parent < 0 ? 0 : pr->parent + 1);
    gbuf_printf(b, "Insns:\t%llu\n", (unsigned long long)pr->insns);
    if (pr->zombie || pr->done)
        gbuf_printf(b, "ExitCode:\t%d\n", pr->rc);
    if (pr->fatal)
        gbuf_printf(b, "Fatal:\t1\n");
}

/****************************************************************
 * Public API
 ****************************************************************/

void *
procfs_open(struct sched *S, int caller_slot, const char *rel, int *err)
{
    struct procfs_open *o;
    int kind, slot, rc;

    rc = resolve(S, caller_slot, rel, &kind, &slot);
    if (rc < 0) {
        *err = rc;
        return NULL;
    }
    o = calloc(1, sizeof *o);
    if (!o) {
        *err = -ENOMEM;
        return NULL;
    }
    o->S = S;
    o->kind = kind;
    o->slot = slot;
    if (kind == PF_FILE)
        gen_status(S, slot, &o->buf);
    *err = 0;
    return o;
}

int
procfs_is_dir(const void *h)
{
    const struct procfs_open *o = h;
    return o->kind != PF_FILE;
}

int
procfs_read(void *h, void *buf, int n)
{
    struct procfs_open *o = h;
    int64_t avail;

    if (o->kind != PF_FILE)
        return -EISDIR;
    if (n <= 0)
        return 0;
    avail = (int64_t)o->buf.len - o->pos;
    if (avail <= 0)
        return 0;                           /* end of file */
    if ((int64_t)n > avail)
        n = (int)avail;
    memcpy(buf, o->buf.p + o->pos, (size_t)n);
    o->pos += n;
    return n;
}

int64_t
procfs_lseek(void *h, int64_t off, int whence)
{
    struct procfs_open *o = h;
    int64_t base;

    if (o->kind != PF_FILE)
        return -EISDIR;
    switch (whence) {
    case FS_SEEK_SET: base = 0; break;
    case FS_SEEK_CUR: base = o->pos; break;
    case FS_SEEK_END: base = (int64_t)o->buf.len; break;
    default:          return -EINVAL;
    }
    if (base + off < 0)
        return -EINVAL;
    o->pos = base + off;
    return o->pos;
}

/* Write one directory entry (name + type) into `de`, or report the end. */
int
procfs_getdent(void *h, struct fs_dirent *de)
{
    struct procfs_open *o = h;

    memset(de, 0, sizeof *de);
    if (o->kind == PF_PID) {
        if (o->index != 0)
            return 0;
        o->index = 1;
        de->ino = (uint32_t)(o->slot + 1);
        de->type = FS_DT_REG;
        strcpy(de->name, "status");
        return 1;
    }
    if (o->kind == PF_ROOT) {
        int want, i, seen;

        if (o->index == 0) {                /* "self" first */
            o->index = 1;
            de->ino = 1;
            de->type = FS_DT_DIR;
            strcpy(de->name, "self");
            return 1;
        }
        want = o->index - 1;                /* the want-th live process */
        seen = 0;
        for (i = 0; i < SKJ_MAX_PROC; i++) {
            if (!o->S->procs[i])
                continue;
            if (seen == want) {
                o->index++;
                de->ino = (uint32_t)(i + 1);
                de->type = FS_DT_DIR;
                snprintf(de->name, FS_DIRENT_NAMEMAX, "%d", i + 1);
                return 1;
            }
            seen++;
        }
        return 0;                           /* no more live processes */
    }
    return -EISDIR;                          /* a file is not iterable */
}

void
procfs_rewind1(void *h)
{
    struct procfs_open *o = h;

    if ((o->kind == PF_ROOT || o->kind == PF_PID) && o->index > 0)
        o->index--;
}

static void
fill_stat(int is_dir, int64_t size, struct fs_stat *st)
{
    memset(st, 0, sizeof *st);
    st->dev = 0x70726f63;                   /* 'proc': a constant procfs device */
    st->ino = 0;
    st->size = size;
    st->mode = is_dir ? (FS_S_IFDIR | 0555u) : (FS_S_IFREG | 0444u);
    st->nlink = 1;
}

int
procfs_fstat(const void *h, struct fs_stat *st)
{
    const struct procfs_open *o = h;

    fill_stat(o->kind != PF_FILE, (int64_t)o->buf.len, st);
    return 0;
}

int
procfs_stat(struct sched *S, int caller_slot, const char *rel, struct fs_stat *st)
{
    int kind, slot, rc;

    rc = resolve(S, caller_slot, rel, &kind, &slot);
    if (rc < 0)
        return rc;
    fill_stat(kind != PF_FILE, 0, st);      /* size unknown without generating */
    return 0;
}

void
procfs_free(void *h)
{
    struct procfs_open *o = h;

    if (!o)
        return;
    gbuf_free(&o->buf);
    free(o);
}
