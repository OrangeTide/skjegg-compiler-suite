/* bin2c: emit a C translation unit and header that expose a file's bytes as a
   byte array, for embedding a data file in a program.  Usage:

       bin2c NAME infile out.c out.h

   The generated unit defines `const unsigned char NAME[]` and
   `const size_t NAME_len`; the header declares them.  Plain ISO C so it builds
   with any host compiler. */

#include <stdio.h>
#include <stdlib.h>

int
main(int argc, char **argv)
{
    const char *name, *inpath, *cpath, *hpath;
    FILE *in, *out, *hdr;
    size_t n = 0;
    int col = 0;
    int ch;

    if (argc != 5) {
        fprintf(stderr, "usage: bin2c NAME infile out.c out.h\n");
        return 2;
    }
    name = argv[1];
    inpath = argv[2];
    cpath = argv[3];
    hpath = argv[4];

    in = fopen(inpath, "rb");
    if (!in) {
        perror(inpath);
        return 1;
    }

    hdr = fopen(hpath, "wb");
    if (!hdr) {
        perror(hpath);
        fclose(in);
        return 1;
    }
    fprintf(hdr,
            "/* generated by bin2c; do not edit */\n"
            "#ifndef %s_H\n#define %s_H\n"
            "#include <stddef.h>\n"
            "extern const unsigned char %s[];\n"
            "extern const size_t %s_len;\n"
            "#endif\n",
            name, name, name, name);
    fclose(hdr);

    out = fopen(cpath, "wb");
    if (!out) {
        perror(cpath);
        fclose(in);
        return 1;
    }
    fprintf(out,
            "/* generated by bin2c; do not edit */\n"
            "#include \"%s.h\"\n"
            "const unsigned char %s[] = {\n",
            name, name);
    while ((ch = fgetc(in)) != EOF) {
        fprintf(out, "%d,", ch);
        if (++col == 20) {
            fputc('\n', out);
            col = 0;
        }
        n++;
    }
    fprintf(out, "\n};\nconst size_t %s_len = %lu;\n", name, (unsigned long)n);

    if (ferror(in) || ferror(out)) {
        fprintf(stderr, "bin2c: I/O error\n");
        fclose(in);
        fclose(out);
        return 1;
    }
    fclose(in);
    fclose(out);
    return 0;
}
